import { WORKFLOW_STATUS } from '../enums/workflowStatus.js';

/**
 * Declarative maker-checker state machine. Consumed by WorkflowEngine.
 *
 *   DRAFT -> VALIDATED -> PENDING_AUTHORISATION -> APPROVED -> POSTED | ACTIVE
 *   PENDING_AUTHORISATION -> RETURNED_FOR_CORRECTION -> RESUBMITTED -> PENDING_AUTHORISATION
 *   PENDING_AUTHORISATION -> REJECTED
 *   POSTED -> REVERSED (only via a linked reversal transaction)
 */
export const WORKFLOW_TRANSITIONS = Object.freeze({
  [WORKFLOW_STATUS.DRAFT]: [
    WORKFLOW_STATUS.VALIDATED,
    WORKFLOW_STATUS.CANCELLED,
  ],
  [WORKFLOW_STATUS.VALIDATED]: [
    WORKFLOW_STATUS.PENDING_AUTHORISATION,
    WORKFLOW_STATUS.DRAFT,
    WORKFLOW_STATUS.CANCELLED,
  ],
  [WORKFLOW_STATUS.PENDING_AUTHORISATION]: [
    WORKFLOW_STATUS.APPROVED,
    WORKFLOW_STATUS.REJECTED,
    WORKFLOW_STATUS.RETURNED_FOR_CORRECTION,
  ],
  [WORKFLOW_STATUS.RETURNED_FOR_CORRECTION]: [
    WORKFLOW_STATUS.RESUBMITTED,
    WORKFLOW_STATUS.CANCELLED,
  ],
  [WORKFLOW_STATUS.RESUBMITTED]: [
    WORKFLOW_STATUS.PENDING_AUTHORISATION,
    WORKFLOW_STATUS.CANCELLED,
  ],
  [WORKFLOW_STATUS.APPROVED]: [
    WORKFLOW_STATUS.POSTED,
    WORKFLOW_STATUS.ACTIVE,
  ],
  [WORKFLOW_STATUS.POSTED]: [
    WORKFLOW_STATUS.REVERSED,
  ],
  [WORKFLOW_STATUS.ACTIVE]: [],
  [WORKFLOW_STATUS.REJECTED]: [],
  [WORKFLOW_STATUS.CANCELLED]: [],
  [WORKFLOW_STATUS.REVERSED]: [],
  [WORKFLOW_STATUS.FAILED]: [],
});
